def _batch(
    prefix: str,
    category: str,
    rows: list[tuple[str, str, str, str]],
) -> list[dict]:
    """rows: (suffix, mode, user, assistant)"""
    out = []
    for suffix, mode, user, asst in rows:
        out.append(
            sft(
                f"{prefix}_{suffix}",
                user,
                asst,
                category=category,
                personality_mode=mode,
                personality_required=mode != "professional_neutral",
                difficulty="medium",
                expected_behavior=f"{category}_expansion",
                safety_sensitive=mode == "serious_no_humor"
                and any(
                    k in user.lower()
                    for k in ("leak", "incident", "password", "breach", "distress", "suicide")
                ),
                tool_required=category == "tool_routing"
                and any(k in user.lower() for k in ("calculate", "time", "timezone", "%", "tool")),
            )
        )
    return out


