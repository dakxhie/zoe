class StrictJSONError(ValueError):
    def __init__(self, detail: str) -> None:
        super().__init__(detail)
        self.detail = detail


def _reject_constant(_name: str) -> Any:
    raise StrictJSONError("non_finite_number")


def _object_pairs(pairs: list[tuple[str, Any]]) -> dict[str, Any]:
    out: dict[str, Any] = {}
    for key, value in pairs:
        if key in out:
            raise StrictJSONError("duplicate_key")
        out[key] = value
    return out


def _parse_int(text: str) -> int:
    if len(text) > MAX_JSON_NUMBER_CHARS:
        raise StrictJSONError("number_too_large")
    return int(text)


def _parse_float(text: str) -> float:
    if len(text) > MAX_JSON_NUMBER_CHARS:
        raise StrictJSONError("number_too_large")
    value = float(text)
    if not math.isfinite(value):
        raise StrictJSONError("non_finite_number")
    return value


def _check_json_value(value: Any, depth: int = 1) -> None:
    if depth > MAX_JSON_DEPTH:
        raise StrictJSONError("too_deep")
    if isinstance(value, str):
        try:
            value.encode("utf-8")
        except UnicodeEncodeError as exc:
            raise StrictJSONError("invalid_string") from exc
    elif isinstance(value, dict):
        for key, item in value.items():
            _check_json_value(key, depth + 1)
            _check_json_value(item, depth + 1)
    elif isinstance(value, list):
        for item in value:
            _check_json_value(item, depth + 1)


def strict_json_loads(text: str) -> Any:
    """Parse JSON strictly; raise ``StrictJSONError`` with a detail code. No repair."""
    if not isinstance(text, str):
        raise StrictJSONError("not_text")
    try:
        value = json.loads(
            text,
            object_pairs_hook=_object_pairs,
            parse_constant=_reject_constant,
            parse_int=_parse_int,
            parse_float=_parse_float,
        )
    except StrictJSONError:
        raise
    except RecursionError as exc:
        raise StrictJSONError("too_deep") from exc
    except (ValueError, TypeError) as exc:
        raise StrictJSONError("invalid_json") from exc
    _check_json_value(value)
    return value


