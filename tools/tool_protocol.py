@dataclass(frozen=True)
class ToolCall:
    """The internal tool-call record (§8.2). Frozen; arguments are deep-frozen.

    ``id``, ``turn_id`` and ``step`` come from the orchestrator and are
    authoritative. ``reason`` is optional free text (<= 200 chars) used only for
    logs and debug views; it never affects authorization.
    """

    tool: str
    arguments: Mapping[str, Any]
    tool_version: str
    id: str
    turn_id: str
    step: int
    reason: str | None = None
    protocol: str = PROTOCOL

    def __post_init__(self) -> None:
        if not isinstance(self.tool, str) or not _TOOL_NAME_RE.match(self.tool):
            raise ProtocolError("invalid_tool_name")
        if not isinstance(self.arguments, Mapping):
            raise ProtocolError("arguments_not_object")
        if not isinstance(self.tool_version, str) or not _VERSION_RE.match(self.tool_version):
            raise ProtocolError("invalid_tool_version")
        if not isinstance(self.id, str) or not _CALL_ID_RE.match(self.id):
            raise ProtocolError("invalid_call_id")
        if not isinstance(self.turn_id, str) or not _TURN_ID_RE.match(self.turn_id):
            raise ProtocolError("invalid_turn_id")
        if isinstance(self.step, bool) or not isinstance(self.step, int) or self.step < 1:
            raise ProtocolError("invalid_step")
        if self.reason is not None:
            if not isinstance(self.reason, str) or len(self.reason) > MAX_REASON_CHARS:
                raise ProtocolError("invalid_reason")
            if _CONTROL_CHARS.search(self.reason):
                raise ProtocolError("invalid_reason")
        if not isinstance(self.protocol, str) or not 1 <= len(self.protocol) <= 32:
            raise ProtocolError("invalid_protocol")
        object.__setattr__(self, "arguments", freeze(self.arguments))

    def arguments_dict(self) -> dict[str, Any]:
        return thaw(self.arguments)


class CallIdAllocator:
    """Orchestrator-side generator of call ids, unique for the session."""

    def __init__(self) -> None:
        self._issued: set[str] = set()
        self._lock = threading.Lock()

    def issue(self) -> str:
        with self._lock:
            while True:
                call_id = f"call_{uuid.uuid4().hex[:24]}"
                if call_id not in self._issued:
                    self._issued.add(call_id)
                    return call_id

    def issued(self, call_id: str) -> bool:
        return call_id in self._issued


def new_turn_id() -> str:
    """Orchestrator-side turn id."""
    return f"turn_{uuid.uuid4().hex[:16]}"


