"""Phase C structured tool protocol and single-call executor.

ZOE_PHASE_A1_DESIGN.md §8.2 (tool call), §8.3/§24 (universal result envelope),
§8.4 (error taxonomy), §8.5 (executor contract), §10.1/§10.2 (Qwen wire format,
fabricated ``<tool_response>``), §22.3 (closed PolicyGate inputs).

This module holds:

- ``ToolCall``: the internal, frozen call record. Its ``id`` is generated by the
  orchestrator (``CallIdAllocator``); ids the model writes are ignored.
- ``strict_json_loads``: strict JSON (duplicate keys, NaN/Infinity, huge
  numbers, lone surrogates and over-deep nesting are rejected; no repair).
- ``QwenToolCallAdapter``: parses Qwen ``<tool_call>{"name": ..., "arguments":
  {...}}</tool_call>`` blocks into ``ToolCall`` records, with oversized-call
  limits and at most ``MAX_CALLS_PER_STEP`` calls per parse step.
  Model-supplied ``id`` / ``call_id`` / ``turn_id`` / ``step`` fields are
  tolerated and dropped (never authoritative); any other unexpected field is
  rejected. A ``<tool_response>`` block written by the model is fabricated: the
  block (including any ``<tool_call>`` nested inside it) is stripped and can
  never become a tool result, a call or an authorization; parsing continues
  normally after it. An unclosed ``<tool_response>`` is stripped to the end of
  the output; a stray ``</tool_response>`` tag is stripped.
- ``PolicyGate``: the authorization step. Its only inputs are the tool
  definition and the validated arguments (plus the turn-scoped B2 web decision
  derived from the current user message). The model's ``reason`` text is not
  an input.
- ``ToolExecutor``: the one execution authority for structured calls, in this
  fixed order: registry lookup -> version validation -> argument validation ->
  policy gate -> timeout boundary -> tool execution -> secret scan -> output
  schema validation -> universal result envelope (``tools.result_envelope.
  bound_result``). Every outcome is an envelope whose ``call_id`` is the
  ``ToolCall.id``; nothing raises past it and no traceback reaches the model or
  the user.

Phase C is not the model loop: nothing here calls the model, iterates, keeps
turn budgets, or is wired into ``brain/pipeline.py`` (that is Phase D).
"""

