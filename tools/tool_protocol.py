class _Timeout(Exception):
    pass


def _run_with_timeout(handler: Any, arguments: dict[str, Any], timeout_s: float, call_id: str) -> Any:
    """Run ``handler`` in a daemon thread that inherits the caller's context.

    On timeout the result is discarded (the thread cannot be killed; its
    output never reaches the envelope).
    """
    context = contextvars.copy_context()
    box: dict[str, Any] = {}
    done = threading.Event()

    def _invoke() -> Any:
        _EXECUTING.set(call_id)
        return handler(**arguments)

    def _runner() -> None:
        try:
            box["value"] = context.run(_invoke)
        except BaseException as exc:  # re-raised in the caller below
            box["error"] = exc
        finally:
            done.set()

    worker = threading.Thread(target=_runner, name=f"zoe-tool-{call_id}", daemon=True)
    worker.start()
    if not done.wait(timeout_s):
        raise _Timeout
    if "error" in box:
        raise box["error"]
    return box["value"]


def _scan_payload(value: Any) -> tuple[Any, int, bool]:
    """Secret-scan every string in a payload: (payload, redacted_lines, blocked)."""
    if isinstance(value, str):
        scan = scan_and_redact(value)
        if scan.blocked:
            return "", 0, True
        if scan.redacted_lines:
            return scan.text, scan.redacted_lines, False
        return value, 0, False
    if isinstance(value, Mapping):
        out: dict[str, Any] = {}
        total = 0
        for key, item in value.items():
            out[key], count, blocked = _scan_payload(item)
            if blocked:
                return None, 0, True
            total += count
        return out, total, False
    if isinstance(value, (list, tuple)):
        items: list[Any] = []
        total = 0
        for item in value:
            scanned, count, blocked = _scan_payload(item)
            if blocked:
                return None, 0, True
            items.append(scanned)
            total += count
        return items, total, False
    return value, 0, False


class ToolExecutor:
    """The single execution authority for structured tool calls (§8.5, §22)."""

    def __init__(self, registry: "ToolRegistry | None" = None, gate: PolicyGate | None = None) -> None:
        if registry is None:
            from tools.tool_catalog import get_tool_registry

            registry = get_tool_registry()
        self.registry = registry
        self.gate = gate or PolicyGate()
        self._executed: set[str] = set()
        self._lock = threading.Lock()

    # -- envelopes ---------------------------------------------------------

    @staticmethod
    def _failure(
        call: ToolCall,
        tool: str,
        status: ResultStatus,
        error_type: str,
        message: str,
        *,
        trust: str = "untrusted",
        metadata: dict[str, Any] | None = None,
    ) -> dict[str, Any]:
        meta = {"turn_id": call.turn_id, "step": call.step, **(metadata or {})}
        if error_type in CANONICAL_ERROR_TYPES:
            return error_envelope(
                tool, status, ErrorType(error_type), message, call_id=call.id, trust=trust, metadata=meta
            )
        envelope = make_envelope(tool, status, call_id=call.id, trust=trust, metadata=meta)
        envelope["error"] = {"type": error_type, "message": message, "retryable": False}
        return envelope

    # -- execution ---------------------------------------------------------

    def execute(self, call: ToolCall) -> dict[str, Any]:
        """Run one call through the fixed pipeline; always return an envelope."""
        try:
            return self._execute(call)
        except Exception as exc:  # last-resort boundary: never raise, never leak
            log_safe_exception(logger, "Tool executor", exc)
            if not isinstance(call, ToolCall):
                raise TypeError("execute() needs a ToolCall") from None
            return self._failure(call, call.tool, ResultStatus.ERROR, INTERNAL_ERROR, UNEXPECTED_TOOL_MESSAGE)

    def _execute(self, call: ToolCall) -> dict[str, Any]:
        if not isinstance(call, ToolCall):
            raise TypeError("execute() needs a ToolCall")
        with self._lock:
            if call.id in self._executed:
                return self._failure(call, call.tool, ResultStatus.ERROR, MALFORMED_CALL, "This call id was already used.")
            self._executed.add(call.id)

        # 1. Registry lookup.
        definition = self.registry.get(call.tool)
        if definition is None:
            return self._failure(call, call.tool, ResultStatus.ERROR, UNKNOWN_TOOL, "There is no tool with that name.")
        tool = definition.name
        trust = definition.trust.value

        # 2. Protocol / version validation.
        if call.protocol != PROTOCOL:
            return self._failure(call, tool, ResultStatus.ERROR, UNSUPPORTED_VERSION, "Unsupported tool protocol.", trust=trust)
        if call.tool_version.split(".", 1)[0] != definition.version_string:
            return self._failure(
                call, tool, ResultStatus.ERROR, UNSUPPORTED_VERSION, "Unsupported tool version.", trust=trust
            )

        # 3. Argument validation (closed schema, defaults applied).
        try:
            arguments = definition.validate_arguments(call.arguments_dict())
        except ArgumentError as exc:
            return self._failure(
                call, tool, ResultStatus.ERROR, INVALID_ARGUMENTS, f"Invalid arguments: {exc.field} {exc.reason}.", trust=trust
            )

        # 4. Policy gate (reason is not an input).
        decision = self.gate.check(definition, arguments)
        audit_logger.info(
            "tool_decision call=%s turn=%s step=%s tool=%s decision=%s error_type=%s",
            call.id,
            call.turn_id,
            call.step,
            definition.id,
            "allow" if decision.allowed else "deny",
            decision.error_type or "-",
        )
        if not decision.allowed:
            return self._failure(
                call, tool, decision.status, decision.error_type or PERMISSION_DENIED, decision.message, trust=trust
            )

        # 5/6. Timeout boundary around tool execution.
        started = time.perf_counter()
        try:
            payload = _run_with_timeout(definition.handler, arguments, definition.timeout_s, call.id)
        except _Timeout:
            logger.warning("Tool %s timed out after %.1fs", definition.id, definition.timeout_s)
            return self._failure(call, tool, ResultStatus.TIMEOUT, ErrorType.TIMEOUT.value, TIMEOUT_MESSAGE, trust=trust)
        except ToolError as exc:
            return self._failure(call, tool, exc.status, exc.error_type, exc.message, trust=trust)
        except TypedSafeError as exc:  # B3 calculator errors (and other typed safe errors)
            return self._failure(call, tool, ResultStatus.ERROR, exc.error_type, exc.safe_message, trust=trust)
        except Exception as exc:
            from tools.fs_policy import FilesystemError

            if isinstance(exc, FilesystemError):  # B1 typed errors keep their types
                status = ResultStatus.DENIED if exc.error_type in FILESYSTEM_DENIED_TYPES else ResultStatus.ERROR
                return self._failure(call, tool, status, exc.error_type, str(exc), trust=trust)
            log_safe_exception(logger, f"Tool {definition.id}", exc)
            return self._failure(call, tool, ResultStatus.ERROR, INTERNAL_ERROR, UNEXPECTED_TOOL_MESSAGE, trust=trust)
        duration_ms = int((time.perf_counter() - started) * 1000)

        # 7. Secret scan over every string in the payload.
        scanned, redactions, blocked = _scan_payload(payload)
        if blocked:
            return self._failure(call, tool, ResultStatus.DENIED, SENSITIVE_CONTENT, SECRET_BLOCKED_MESSAGE, trust=trust)

        # 8. Output schema validation.
        try:
            result = definition.validate_result(scanned)
        except ArgumentError:
            logger.warning("Tool %s returned an invalid result shape", definition.id)
            return self._failure(call, tool, ResultStatus.ERROR, INTERNAL_ERROR, INVALID_RESULT_MESSAGE, trust=trust)

        # 9. Universal result envelope (per-tool limits, then global limits).
        source: dict[str, Any] = {"kind": definition.source_kind}
        if definition.source_kind == "file" and isinstance(result.get("path"), str):
            source["path"] = result["path"]
        return bound_result(
            tool,
            result,
            trust=trust,
            source=source,
            metadata={
                "duration_ms": duration_ms,
                # Lines redacted by the tool itself (B1 reports them) plus the executor scan.
                "redactions": redactions + (result["redactions"] if isinstance(result.get("redactions"), int) else 0),
                "turn_id": call.turn_id,
                "step": call.step,
            },
            tool_limits=definition.limits,
            call_id=call.id,
        )


_default_executor: ToolExecutor | None = None
_default_lock = threading.Lock()


def get_tool_executor() -> ToolExecutor:
    """The process-wide executor instance (one execution authority)."""
    global _default_executor
    with _default_lock:
        if _default_executor is None:
            _default_executor = ToolExecutor()
        return _default_executor


def execute_tool_call(call: ToolCall) -> dict[str, Any]:
    """Execute one structured call through the single ToolExecutor."""
    return get_tool_executor().execute(call)
