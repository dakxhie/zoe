@dataclass(frozen=True)
class ParseError:
    """Why a parse step produced no calls. ``type`` is always ``malformed_call``."""

    detail: str
    index: int | None = None
    type: str = MALFORMED_CALL


@dataclass(frozen=True)
class ParseResult:
    """Outcome of one parse step. On any error, ``calls`` is empty (fail closed)."""

    calls: tuple[ToolCall, ...] = ()
    error: ParseError | None = None
    fabricated_tool_response: bool = False
    fabricated_responses: int = 0  # number of stripped <tool_response> blocks / stray tags
    text: str = ""  # model prose outside tool-call blocks (not instructions)

    @property
    def ok(self) -> bool:
        return self.error is None


def _split_blocks(text: str) -> tuple[list[str], str, int]:
    """Return the raw ``<tool_call>`` payloads, the remaining prose and the fabrication count.

    One left-to-right scan; whichever tag starts first wins:

    - ``<tool_call>`` ... ``</tool_call>``: a call payload (no nesting).
    - ``<tool_response ...>`` ... ``</tool_response>``: fabricated by the model;
      stripped entirely, including any ``<tool_call>`` inside it. Without a
      closing tag it is stripped to the end of the output (fail closed).
    - a stray ``</tool_response>``: stripped.
    - a stray ``</tool_call>``: malformed.
    """
    payloads: list[str] = []
    prose: list[str] = []
    fabricated = 0
    position = 0
    length = len(text)
    while position < length:
        call_open = text.find(TOOL_CALL_OPEN, position)
        call_close = text.find(TOOL_CALL_CLOSE, position)
        response_open = _RESPONSE_OPEN.search(text, position)
        response_close = _RESPONSE_CLOSE.search(text, position)
        candidates = [
            (call_open, "call_open"),
            (call_close, "call_close"),
            (response_open.start() if response_open else -1, "response_open"),
            (response_close.start() if response_close else -1, "response_close"),
        ]
        found = [(index, kind) for index, kind in candidates if index != -1]
        if not found:
            prose.append(text[position:])
            break
        start, kind = min(found)
        prose.append(text[position:start])
        if kind == "call_close":
            raise ProtocolError("unmatched_close_tag")
        if kind == "response_open":
            fabricated += 1
            closing = _RESPONSE_CLOSE.search(text, response_open.end())
            position = closing.end() if closing else length
            continue
        if kind == "response_close":
            fabricated += 1
            position = response_close.end()
            continue
        body_start = start + len(TOOL_CALL_OPEN)
        end = text.find(TOOL_CALL_CLOSE, body_start)
        if end == -1:
            raise ProtocolError("unclosed_block")
        body = text[body_start:end]
        if TOOL_CALL_OPEN in body:
            raise ProtocolError("nested_block")
        payloads.append(body)
        position = end + len(TOOL_CALL_CLOSE)
    return payloads, "".join(prose).strip(), fabricated


class QwenToolCallAdapter:
    """Map Qwen's native ``{"name", "arguments"}`` wire calls to ``ToolCall`` records."""

    def __init__(self, registry: "ToolRegistry | None" = None, ids: CallIdAllocator | None = None) -> None:
        if registry is None:
            from tools.tool_catalog import get_tool_registry

            registry = get_tool_registry()
        self.registry = registry
        self.ids = ids or CallIdAllocator()

    def parse(self, model_output: str, *, turn_id: str, step: int) -> ParseResult:
        """Parse one model output. ``turn_id`` and ``step`` are the orchestrator's."""
        if not isinstance(model_output, str):
            return ParseResult(error=ParseError("not_text"))
        if len(model_output) > MAX_MODEL_OUTPUT_CHARS:
            return ParseResult(error=ParseError("oversized_output"))

        # §10.2: a model-written <tool_response> is stripped by the scan (never a
        # tool result, call or authorization); parsing continues after it.
        try:
            payloads, prose, fabricated_count = _split_blocks(model_output)
        except ProtocolError as exc:
            seen = bool(_RESPONSE_OPEN.search(model_output) or _RESPONSE_CLOSE.search(model_output))
            return ParseResult(error=ParseError(exc.detail), fabricated_tool_response=seen)
        fabricated = fabricated_count > 0
        if fabricated:
            audit_logger.warning(
                "fabricated_tool_response turn=%s step=%s count=%d", turn_id, step, fabricated_count
            )
        if len(payloads) > MAX_CALLS_PER_STEP:
            return ParseResult(error=ParseError("too_many_calls"), fabricated_tool_response=fabricated)

        drafts: list[dict[str, Any]] = []
        for index, payload in enumerate(payloads):
            if len(payload) > MAX_TOOL_CALL_CHARS:
                return ParseResult(error=ParseError("oversized_call", index), fabricated_tool_response=fabricated)
            try:
                drafts.append(self._draft(strict_json_loads(payload)))
            except (StrictJSONError, ProtocolError) as exc:
                return ParseResult(error=ParseError(exc.detail, index), fabricated_tool_response=fabricated)

        calls: list[ToolCall] = []
        for index, draft in enumerate(drafts):
            try:
                calls.append(
                    ToolCall(
                        tool=draft["tool"],
                        arguments=draft["arguments"],
                        tool_version=draft["tool_version"],
                        id=self.ids.issue(),
                        turn_id=turn_id,
                        step=step,
                        reason=draft["reason"],
                    )
                )
            except ProtocolError as exc:
                return ParseResult(error=ParseError(exc.detail, index), fabricated_tool_response=fabricated)
        return ParseResult(
            calls=tuple(calls),
            fabricated_tool_response=fabricated,
            fabricated_responses=fabricated_count,
            text=prose,
        )

    def _draft(self, wire: Any) -> dict[str, Any]:
        if not isinstance(wire, dict):
            raise ProtocolError("call_not_object")
        unknown = set(wire) - _WIRE_KEYS - _IGNORED_WIRE_KEYS
        if unknown:
            raise ProtocolError("unknown_call_field")
        # Model-supplied id / call_id / turn_id / step: dropped here, unread.
        wire = {key: value for key, value in wire.items() if key not in _IGNORED_WIRE_KEYS}
        name = wire.get("name")
        if not isinstance(name, str) or not _TOOL_NAME_RE.match(name):
            raise ProtocolError("invalid_tool_name")
        if "arguments" not in wire or not isinstance(wire["arguments"], dict):
            raise ProtocolError("arguments_not_object")
        reason = wire.get("reason")
        if reason is not None and (not isinstance(reason, str) or len(reason) > MAX_REASON_CHARS):
            raise ProtocolError("invalid_reason")
        tool = self.registry.resolve_wire_name(name)
        definition = self.registry.get(tool)
        version = wire.get("tool_version")
        if version is None:
            version = definition.version_string if definition is not None else "1"
        if not isinstance(version, str):
            raise ProtocolError("invalid_tool_version")
        return {"tool": tool, "arguments": wire["arguments"], "tool_version": version, "reason": reason}


