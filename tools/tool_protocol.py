MAX_REASON_CHARS = 200  # §8.2
MAX_CALLS_PER_STEP = 3  # §10.3 (PARSE -> POLICY with N <= 3 per step)
MAX_TOOL_CALL_CHARS = 4096  # one <tool_call> JSON payload
MAX_MODEL_OUTPUT_CHARS = 32 * 1024  # whole model output considered for parsing
MAX_JSON_DEPTH = 8
MAX_JSON_NUMBER_CHARS = 32
MAX_TOOL_NAME_CHARS = 64

TOOL_CALL_OPEN = "<tool_call>"
TOOL_CALL_CLOSE = "</tool_call>"
# Fabricated tool responses (§10.2). Case-insensitive, tolerant of spacing and
# attributes so variants cannot slip through as prose that later looks real.
_RESPONSE_OPEN = re.compile(r"<\s*tool_response\b", re.IGNORECASE)
_RESPONSE_CLOSE = re.compile(r"<\s*/\s*tool_response\b[^>]*>?", re.IGNORECASE)

# Expected wire fields (Qwen ``name`` / ``arguments`` plus optional ``reason``
# and ``tool_version``, both validated).
_WIRE_KEYS = frozenset({"name", "arguments", "reason", "tool_version"})
# Model-supplied metadata: tolerated on the wire, NEVER authoritative, dropped
# before a ToolCall is built. Their values are ignored whatever their type, but
# the whole payload still passed strict JSON (duplicate keys, NaN/Infinity,
# number size, depth) and the per-call size limit. The orchestrator alone
# supplies ``ToolCall.id`` / ``turn_id`` / ``step``.
_IGNORED_WIRE_KEYS = frozenset({"id", "call_id", "turn_id", "step"})

_CALL_ID_RE = re.compile(r"^call_[0-9a-f]{24}$")
_TURN_ID_RE = re.compile(r"^[A-Za-z0-9_\-]{1,64}$")
_TOOL_NAME_RE = re.compile(r"^[A-Za-z0-9_.\-]{1,%d}$" % MAX_TOOL_NAME_CHARS)
_VERSION_RE = re.compile(r"^[1-9][0-9]{0,3}(?:\.[0-9]{1,4}){0,2}$")
_CONTROL_CHARS = re.compile(r"[\x00-\x08\x0b-\x1f\x7f]")

